package ee.schimke.composeai.cli.serve

import ee.schimke.composeai.cli.serve.UiBuilderExportComparison.Outcome
import ee.schimke.composeai.cli.serve.UiBuilderExportComparison.Row
import ee.schimke.composeai.cli.serve.UiBuilderExportComparison.Verdict
import kotlin.io.path.createTempDirectory
import kotlin.test.Test
import kotlin.test.assertEquals

/** The comparison's own logic; the export it drives is the host's, tested where it lives. */
class UiBuilderExportComparisonTest {

  @Test
  fun `the provenance header is dropped, since it names the pin and always differs`() {
    val source =
      "// Generated by compose-preview serve from a UI-builder design.\n" +
        "// Catalog m3-catalog@candidate; capability x\n" +
        "\n" +
        "package generated.uibuilder\n"
    assertEquals(
      "package generated.uibuilder\n",
      UiBuilderExportComparison.withoutProvenance(source),
    )
    // A source with no header block keeps its leading comment.
    val bare = "// a note\npackage generated.uibuilder\n"
    assertEquals(bare, UiBuilderExportComparison.withoutProvenance(bare))
  }

  @Test
  fun `each pair of outcomes has one verdict`() {
    val same = Outcome.Emitted("Text()")
    val refused = Outcome.Refused(listOf("UNEXPRESSIBLE: no"))
    assertEquals(Verdict.IDENTICAL, Row("d", same, Outcome.Emitted("Text()")).verdict)
    assertEquals(Verdict.DIFFERS, Row("d", same, Outcome.Emitted("Card()")).verdict)
    assertEquals(Verdict.ONLY_A, Row("d", same, refused).verdict)
    assertEquals(Verdict.ONLY_B, Row("d", refused, same).verdict)
    assertEquals(Verdict.BOTH_REFUSED, Row("d", refused, refused).verdict)
  }

  @Test
  fun `the diff marks removed and added lines and keeps context`() {
    val a = "Column {\n  Text(\"a\")\n  Button()\n}"
    val b = "Column {\n  Text(\"a\")\n  FilledButton()\n}"
    assertEquals(
      " Column {\n   Text(\"a\")\n-  Button()\n+  FilledButton()\n }\n",
      UiBuilderExportComparison.lineDiff(a, b),
    )
    // Identical sources have no hunk at all.
    assertEquals("", UiBuilderExportComparison.lineDiff("x", "x"))
  }

  @Test
  fun `only design documents are compared, not an app's design index beside them`() {
    val dir = createTempDirectory("designs").toFile()
    val design =
      dir.resolve("contacts.uid").apply {
        writeText(
          "{\"schema\": \"compose-ui-builder-document/v1-candidate\", \"id\": \"contacts\"}"
        )
      }
    val index =
      dir.resolve("index.json").apply {
        writeText("{\"schema\": \"compose-ui-builder-design-index/v1\", \"designs\": []}")
      }
    val broken = dir.resolve("broken.json").apply { writeText("{") }
    assertEquals(true, UiBuilderExportComparison.isDesignDocument(design))
    assertEquals(false, UiBuilderExportComparison.isDesignDocument(index))
    assertEquals(false, UiBuilderExportComparison.isDesignDocument(broken))
  }
}
