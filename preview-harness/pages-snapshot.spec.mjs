for (const file of readdirSync(pagesDir).filter((name) =>
  name.endsWith(".html"),
)) {
  const html = readFileSync(resolve(pagesDir, file), "utf8");
  let needsVue = false;
  for (const [tag, assets] of Object.entries(COMPONENT_ASSETS)) {
    if (!html.includes(`<${tag}`)) continue;
    if (!assets.some((asset) => html.includes(asset))) {
      throw new Error(`${file}: <${tag}> requires ${assets.join(" or ")}`);
    }
    if (!assets.includes("serve-chrome.js")) needsVue = true;
  }
  if (needsVue) {
    const runtimeCount = html.match(/vue-runtime\.js/g)?.length ?? 0;
    if (runtimeCount !== 1) {
      throw new Error(
        `${file}: expected one Vue runtime, found ${runtimeCount}`,
      );
    }
  }
}

// Runtime states of a page fixture that the committed HTML can't express, captured as extra shots.
// Each names a base fixture, a filename suffix, and an in-page mutation.
//
// `connecting` covers the live-lane activation badge: set `data-pending` as the viewer JS does and
// let the real `backendBadgeScript` paint it.
//
// openThemeBar: the viewer's theme bar folds behind its title-bar toggle when there are many
// themes, so open the disclosure then press the chip, as a visitor does. A no-op where the bar is
// inline.
async function openThemeBar(page) {
  const bar = page.locator("#cp-theme-bar");
  if ((await bar.count()) && (await bar.isHidden()))
    await page.click("#cp-theme-toggle");
}

/**
 * Open the overrides drawer column (`cp-controls-open` on `.cp-viewer`), which starts closed at
 * every width and hides every group inside it. Through the toggle, and idempotent.
 */
async function openControlsDrawer(page) {
  const viewer = page.locator(".cp-viewer");
  if (!(await viewer.count())) return;
  const open = await viewer.evaluate((v) =>
    v.classList.contains("cp-controls-open"),
  );
  if (!open) await page.click("#cp-controls-toggle");
  await expect(viewer).toHaveClass(/cp-controls-open/);
}

// A point on the design sheet in the export's own user units (where a reader double-clicks to
// zoom). Correct at any zoom, since the SVG's client rect includes the stage transform.
async function sheetPoint(page, ux, uy) {
  const at = await page.evaluate(
    ([x, y]) => {
      const svg = document.querySelector(".cp-page-stage svg");
      const rect = svg.getBoundingClientRect();
      const box = svg.viewBox.baseVal;
      const at = {
        x: rect.left + (x / box.width) * rect.width,
        y: rect.top + (y / box.height) * rect.height,
      };
      // What a real pointer there would hit: `elementFromPoint` returns the topmost element, which
      // is where a `page.mouse` gesture is dispatched.
      const hit = document.elementFromPoint(at.x, at.y);
      return {
        ...at,
        width: window.innerWidth,
        height: window.innerHeight,
        covered: hit && !hit.closest(".cp-page-stage") ? describe(hit) : null,
      };
      function describe(el) {
        const named = el.closest("[class]") ?? el;
        const name =
          typeof named.className === "string" ? named.className : named.tagName;
        return `<${el.tagName.toLowerCase()}> in ${name}`;
      }
    },
    [ux, uy],
  );
  // A zoom can move the target off screen, where a click hits nothing; report that rather than
  // timing out.
  if (at.x < 0 || at.y < 0 || at.x > at.width || at.y > at.height) {
    throw new Error(
      `sheet point ${ux},${uy} is off-screen at (${Math.round(at.x)}, ${Math.round(at.y)}) ` +
        `in a ${at.width}x${at.height} viewport — aim at a spot the current view still shows`,
    );
  }
  // On screen but covered, typically by the sticky control row; name the obstruction.
  if (at.covered) {
    throw new Error(
      `sheet point ${ux},${uy} is covered at (${Math.round(at.x)}, ${Math.round(at.y)}) by ` +
        `${at.covered} — aim clear of the sticky control row, or scroll it out of the way first`,
    );
  }
  return at;
}

/**
 * Scroll the design page so the sheet starts below the sticky control row, as a reader would.
 * Deliberately not inside `sheetPoint`, whose `covered` guard must still report bad aim.
 */
async function revealStage(page) {
  await page.evaluate(() => {
    const stage = document.querySelector(".cp-page-stage");
    const bar = document.querySelector(".cp-page-toolbar");
    // Where the stage's top edge would have to be for the bar to clear it, plus a margin so a
    // point aimed AT that edge is still the sheet's.
    const clearance = bar.getBoundingClientRect().height + 24;
    const top = stage.getBoundingClientRect().top + window.scrollY;
    window.scrollTo({ top: Math.max(0, top - clearance), behavior: "instant" });
  });
}

